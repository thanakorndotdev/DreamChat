export type LegalBlock = { kind: 'h2'; text: string; id?: string } | { kind: 'p'; text: string } | { kind: 'ul'; items: string[] };

export function parseLegal(body: string): LegalBlock[] {
  const blocks: LegalBlock[] = [];
  let para: string[] = [];
  const flush = () => {
    if (para.length) blocks.push({ kind: 'p', text: para.join(' ') });
    para = [];
  };
  for (const raw of body.replace(/\r\n?/g, '\n').split('\n')) {
    const line = raw.trim();
    if (!line) {
      flush();
    } else if (line.startsWith('## ')) {
      flush();
      const m = /^(.*?)\s*\{#([\w-]+)\}$/.exec(line.slice(3));
      blocks.push(m ? { kind: 'h2', text: m[1], id: m[2] } : { kind: 'h2', text: line.slice(3).trim() });
    } else if (line.startsWith('- ')) {
      flush();
      const last = blocks[blocks.length - 1];
      if (last?.kind === 'ul') last.items.push(line.slice(2).trim());
      else blocks.push({ kind: 'ul', items: [line.slice(2).trim()] });
    } else {
      para.push(line);
    }
  }
  flush();
  return blocks;
}

export function fillLegal(text: string, info: { operator: string; contact: string }) {
  return text.replaceAll('{operator}', info.operator).replaceAll('{contact}', info.contact);
}

